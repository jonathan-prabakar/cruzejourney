import { writeFileSync } from 'node:fs';
// Authored approximate corridor anchors, NOT measured GPS or verified road geometry.
// Latitude/longitude follows San Antonio -> New Braunfels -> San Marcos -> Kyle -> Austin.
const anchors = [
  [29.4241, -98.4936], [29.487, -98.405], [29.574, -98.303],
  [29.703, -98.126], [29.774, -98.008], [29.883, -97.942],
  [29.95, -97.87], [30.006, -97.842], [30.083, -97.817],
  [30.167, -97.787], [30.2672, -97.7431],
];
function miles(a, b) {
  const rad = Math.PI / 180;
  const dlat = (b[0] - a[0]) * rad, dlon = (b[1] - a[1]) * rad;
  const h = Math.sin(dlat / 2) ** 2 + Math.cos(a[0] * rad) * Math.cos(b[0] * rad) * Math.sin(dlon / 2) ** 2;
  return 3958.7613 * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
}
const distances = [0];
for (let i = 1; i < anchors.length; i++) distances.push(distances[i - 1] + miles(anchors[i - 1], anchors[i]));
const length = distances.at(-1);
const speeds = Array.from({ length: 241 }, (_, i) => {
  const ramp = Math.min(1, i / 22, (240 - i) / 22);
  return Math.round((28 + 36 * ramp + 3 * Math.sin(i / 11) - 12 * Math.exp(-(((i - 132) / 12) ** 2))) * 100) / 100;
});
const weights = speeds.map((speed, i) => i ? (speed + speeds[i - 1]) / 2 : 0);
const dtHours = length / weights.reduce((a, b) => a + b, 0);
const start = Date.parse('2026-10-01T14:00:00Z');
const round = (n, places = 6) => Number(n.toFixed(places));
let distance = 0, gallons = 120 * 0.17;
const records = speeds.map((speed, i) => {
  const mpg = round(8 + 0.45 * Math.sin(i / 15) - 0.2 * Math.cos(i / 7), 3);
  const step = weights[i] * dtHours;
  distance += step;
  // Each interval uses trapezoidal endpoint speed and the ending record's MPG.
  if (i) gallons -= step / mpg;
  let segment = 1;
  while (segment < distances.length - 1 && distance > distances[segment]) segment++;
  const fraction = Math.max(0, Math.min(1, (distance - distances[segment - 1]) / (distances[segment] - distances[segment - 1])));
  const a = anchors[segment - 1], b = anchors[segment];
  return {
    timestamp: new Date(start + Math.round(i * dtHours * 3600000)).toISOString(),
    latitude: round(a[0] + (b[0] - a[0]) * fraction),
    longitude: round(a[1] + (b[1] - a[1]) * fraction),
    speed_mph: speed,
    rpm: Math.round(800 + speed * 18 + 45 * Math.sin(i / 9)),
    fuel_percent: round(gallons / 120 * 100),
    mpg,
    coolant_temp_f: round(187 + 9 * (1 - Math.exp(-i / 20)) + 2 * Math.sin(i / 18), 2),
    diagnostic_code: i >= 160 && i <= 175 ? 'P0301' : null,
  };
});
const dataset = {
  metadata: {
    name: 'Synthetic San Antonio to Austin low-start-fuel trip',
    source: 'Procedurally generated by scripts/generate-demo.mjs; no real vehicle or external dataset',
    synthetic: true,
    route: 'Synthetic corridor: San Antonio, New Braunfels, San Marcos, Kyle, Austin, Texas',
    limitations: [
      'Approximate authored corridor polyline, not verified road geometry; interpolated positions may be off-road.',
      'Starts at 17% fuel; naturally drops below 10%. No accelerated fuel depletion.',
      'Speed is an interval-endpoint sample; fuel consumption uses trapezoidal speed and ending-record MPG.',
      'All measurements and P0301 events are simulated. No diagnostic interpretation.',
    ],
    vehicle: { name: 'Demo Freight Truck', tank_capacity_gallons: 120, typical_mpg: 8 },
  },
  records,
};
writeFileSync(new URL('../src/data/demo-telemetry.json', import.meta.url), JSON.stringify(dataset, null, 2) + '\n');
